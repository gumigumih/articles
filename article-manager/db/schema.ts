import { sql } from 'drizzle-orm';
import { index, integer, sqliteTable, text, uniqueIndex } from 'drizzle-orm/sqlite-core';
export const articles = sqliteTable('articles', {
 id: integer('id').primaryKey({autoIncrement:true}),
 platform:text('platform').notNull().default('note'),
 sourcePath:text('source_path').notNull().default(''),
 sourceKind:text('source_kind').notNull().default('article'),
 sourceEvidence:text('source_evidence').notNull().default(''),
 title:text('title').notNull(),
 url:text('url').notNull(),
 category:text('category').notNull(),
 memo:text('memo').notNull().default(''),
 status:text('status').notNull().default('未確認'),
 updatedAt:text('updated_at').notNull(),
 slug:text('slug').notNull().default(''),
 noteId:text('note_id').notNull().default(''),
 publicationStatus:text('publication_status').notNull().default('要確認'),
 magazine:text('magazine').notNull().default('未分類'),
 price:integer('price').notNull().default(0),
 publishedAt:text('published_at'),
 lastCheckedAt:text('last_checked_at'),
 gitStatus:text('git_status').notNull().default('clean'),
 coverStatus:text('cover_status').notNull().default('missing'),
 pv:integer('pv').notNull().default(0),
 likes:integer('likes').notNull().default(0),
 metricsFetchedAt:text('metrics_fetched_at'),
 xPosted:integer('x_posted',{mode:'boolean'}).notNull().default(false),
 updateCandidate:integer('update_candidate',{mode:'boolean'}).notNull().default(false),
 bodyPreview:text('body_preview').notNull().default(''),
 markdownState:text('markdown_state').notNull().default('missing'),
 xCopyState:text('x_copy_state').notNull().default('missing'),
 coverPromptState:text('cover_prompt_state').notNull().default('missing'),
 coverFileState:text('cover_file_state').notNull().default('missing'),
 syncedAt:text('synced_at'),
 syncStatus:text('sync_status').notNull().default('stale'),
}, t=>[
 uniqueIndex('articles_source_path_unique').on(t.sourcePath).where(sql`${t.sourcePath} <> ''`),
 uniqueIndex('articles_url_unique').on(t.url).where(sql`${t.url} <> ''`),
 index('idx_articles_publication_status').on(t.publicationStatus),
 index('idx_articles_magazine').on(t.magazine),
 index('idx_articles_git_status').on(t.gitStatus),
]);
